print("Loading spaCy model...")
import spacy
import pandas as pd
nlp = spacy.load("en_core_web_sm")
train_df = pd.read_csv('train.csv')
test_df = pd.read_csv("test.csv")

def preprocess(text):
    doc = nlp(text.lower())
    return " ".join(
        token.lemma_
        for token in doc
        if not token.is_stop
        and not token.is_punct
        and not token.is_space
    )

print("Cleaning text...")

train_df["clean_text"] = train_df["text"].apply(
    preprocess
)

test_df["clean_text"] = test_df["text"].apply(
    preprocess
)

from sklearn.feature_extraction.text import TfidfVectorizer
tfidf = TfidfVectorizer(
    ngram_range=(1, 2),
    max_features=10000
)

X_train = tfidf.fit_transform(
    train_df["clean_text"]
)

X_test = tfidf.transform(
    test_df["clean_text"]
)

y_train = train_df["category"]
y_test = test_df["category"]

from sklearn.linear_model import LogisticRegression
model = LogisticRegression(
    max_iter=1000
)

model.fit(
    X_train,
    y_train
)

print("✅ Model Training Complete")

import numpy as np
def predict_intent(message):
    clean_message = preprocess(message)
    vector = tfidf.transform(
        [clean_message]
    )
    intent = model.predict(
        vector
    )[0]
    probability = np.max(
        model.predict_proba(vector)
    )
    return intent, probability

def generate_response(
    message,
    intent,
    confidence
):
    prompt = f"""
You are SmartBank AI Assistant.

Customer Message:
{message}

Detected Intent:
{intent}

Confidence Score:
{round(confidence*100,2)}%

Generate a short professional banking support response.

Rules:
- Maximum 100 words
- Be helpful
- Do not ask for OTP
- Do not ask for PIN
- Do not ask for passwords
"""
    response = gemini.generate_content(
        prompt
    )
    return response.text

def chatbot(message):
    # Check for simple greeting matches
    greetings = ["hi", "hello", "hey", "greetings"]
    if message.strip().lower() in greetings:
        return """
----------------------------------
Response:
Hello! Welcome to SmartBank. How can I assist you with your banking services today?
----------------------------------
"""

    intent, confidence = predict_intent(
        message
    )

    if confidence < 0.20:
        return (
            "Sorry, I could not understand "
            "your request clearly."
        )

    response = generate_response(
        message,
        intent,
        confidence
    )

    return f"""
----------------------------------
Intent     : {intent}
Confidence : {round(confidence*100,2)}%

Response:
{response}
----------------------------------
"""

